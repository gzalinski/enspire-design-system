#!/usr/bin/env node
/**
 * Enspire icons — components/icon/svg/*.svg  ->  components/icon/glyphs.css
 * Zero dependencies.
 *
 * Each SVG becomes a CSS mask, so an icon is just  <span class="es-icon" data-name="mail">
 * and inherits color from `currentColor`. No sprite, no JS, no inline SVG in the markup —
 * the same markup works in PHP templates, Gutenberg, React and static HTML.
 *
 * To add an icon: drop an SVG (24x24 viewBox, stroke-based, e.g. from Lucide) into
 * components/icon/svg/ and run `npm run icons`. The icon list in meta.json updates itself.
 * Brand logos (Facebook, Instagram, ...) are NOT in Lucide v1 — source them separately.
 */

const fs = require('fs');
const path = require('path');

const DIR = path.resolve(__dirname, '..', 'components', 'icon');
const SVG_DIR = path.join(DIR, 'svg');

/** Inner markup of the SVG, with comments and whitespace squeezed. */
function inner(svg) {
  const body = svg.replace(/<!--[\s\S]*?-->/g, '').match(/<svg[^>]*>([\s\S]*)<\/svg>/);
  if (!body) throw new Error('no <svg> element');
  return body[1].replace(/\s+/g, ' ').replace(/> </g, '><').trim();
}

/** Mask only reads alpha, so the stroke color is irrelevant; the round caps/joins are not. */
function toDataUri(svg) {
  const doc =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="#000" ` +
    `stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${inner(svg)}</svg>`;
  const encoded = encodeURIComponent(doc)
    .replace(/%20/g, ' ')
    .replace(/%3D/g, '=')
    .replace(/%3A/g, ':')
    .replace(/%2F/g, '/')
    .replace(/%2C/g, ',')
    .replace(/\(/g, '%28') // parentheses would end the url() token
    .replace(/\)/g, '%29')
    .replace(/'/g, '%27');
  return `data:image/svg+xml,${encoded}`;
}

const files = fs.readdirSync(SVG_DIR).filter((f) => f.endsWith('.svg')).sort();
const names = [];
const rules = [];

for (const file of files) {
  const name = file.replace(/\.svg$/, '');
  try {
    const uri = toDataUri(fs.readFileSync(path.join(SVG_DIR, file), 'utf8'));
    rules.push(`.es-icon[data-name="${name}"]{--_glyph:url("${uri}");background-color:currentColor}`);
    names.push(name);
  } catch (e) {
    console.error(`\x1b[31m✗\x1b[0m ${file}: ${e.message}`);
    process.exit(1);
  }
}

const css = `/* Enspire icon glyphs — generated by tools/icons.js from components/icon/svg/. Do not edit by hand. */
/* ${names.length} icons · Lucide (ISC), see svg/LICENSE-lucide.txt */
/* An unknown data-name draws nothing (no background is set), rather than a solid square. */

${rules.join('\n')}
`;
fs.writeFileSync(path.join(DIR, 'glyphs.css'), css);

// Keep the meta.json icon list in sync so the index and the Lab never drift from the folder.
const metaPath = path.join(DIR, 'meta.json');
if (fs.existsSync(metaPath)) {
  const meta = JSON.parse(fs.readFileSync(metaPath, 'utf8'));
  meta.variants = { ...meta.variants, name: names };
  fs.writeFileSync(metaPath, JSON.stringify(meta, null, 2) + '\n');
}

console.log(`\x1b[32m✓\x1b[0m ${names.length} icons · ${(css.length / 1024).toFixed(1)} KB · components/icon/glyphs.css`);
