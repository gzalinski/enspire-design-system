#!/usr/bin/env node
/**
 * Generate INDEX.md from every components/<name>/meta.json. Never edit INDEX.md by hand: edit meta.json.
 * It is the first file Claude Code reads, so it stays one line per component.
 */

const fs = require('fs');
const path = require('path');
const { load, ROOT } = require('./components');

const { items, order } = load();

/** Compact axis summary. Long axes (icon names) collapse to a count so the line stays scannable. */
function variantsOf(meta) {
  return Object.entries(meta.variants || {})
    .map(([axis, values]) => (values.length > 8 ? `${axis}(${values.length})` : `${axis}(${values.join('|')})`))
    .join(' ') || '—';
}

const line = (item) => {
  const m = item.meta;
  return `${m.name} | .${m.class} | ${(m.tags || []).join(',')} | ${variantsOf(m)} | ${(m.uses || []).join(',') || '—'} | ${item.path}`;
};

const section = (title, level, empty) => {
  const rows = order.map((n) => items.get(n)).filter((i) => i.level === level).map(line);
  return `## ${title}\n${rows.length ? rows.join('\n') : `<!-- ${empty} -->`}\n`;
};

const out = `# Component index

> Generated by \`npm run index\` from \`components/*/meta.json\`. Do not edit by hand.
> Read this first. If something close exists, extend its variants instead of adding a sibling.
> Level (atom / molecule / organism) is derived from \`uses\`, never declared.

Format: \`name | .class | tags | variants | uses | path\`

${section('Atoms', 'atom', 'none yet')}
${section('Molecules', 'molecule', 'none yet')}
${section('Organisms', 'organism', 'none yet')}
## Patterns
<!-- none yet -->

## Templates
<!-- none yet -->

## Bridges
<!-- none yet — first: gravity-forms (Faza 2) -->

---
${items.size} components
`;

fs.writeFileSync(path.join(ROOT, 'INDEX.md'), out);
console.log(`\x1b[32m✓\x1b[0m INDEX.md · ${items.size} components`);
